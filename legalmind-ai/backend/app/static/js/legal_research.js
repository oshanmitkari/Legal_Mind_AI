/**
 * F7: Legal Research Engine - Client-side Interface
 */

let researchForm, researchQuery, researchResults, loadingOverlay;
let lastResearchResult = null;

// Wait for DOM to load before attaching event listeners
document.addEventListener('DOMContentLoaded', function() {
    researchForm = document.getElementById('researchForm');
    researchQuery = document.getElementById('researchQuery');
    researchResults = document.getElementById('researchResults');
    loadingOverlay = document.getElementById('loadingOverlay');

    // Handle form submission
    if (researchForm) {
        researchForm.addEventListener('submit', async function(e) {
            e.preventDefault();

            const query = researchQuery.value.trim();
            if (!query) return;

            await performResearch(query);
        });
    }
});

/**
 * Perform legal research
 */
async function performResearch(query) {
    // Show loading
    loadingOverlay.style.display = 'block';
    researchResults.style.display = 'none';
    
    try {
        const response = await fetch('/ai/research', {
            method: 'POST',
            headers: {'Content-Type': 'application/json'},
            body: JSON.stringify({query: query})
        });
        
        const data = await response.json();
        
        if (response.ok) {
            lastResearchResult = data;
            displayResults(data);
        } else {
            alert('Error: ' + (data.error || 'Research failed'));
        }
    } catch (error) {
        alert('Failed to perform research: ' + error.message);
    } finally {
        loadingOverlay.style.display = 'none';
    }
}

/**
 * Display research results
 */
function displayResults(data) {
    // Show results container
    researchResults.style.display = 'block';
    
    // Display retrieved sections from FAISS
    const retrievedSections = document.getElementById('retrievedSections');
    const retrievedSectionsList = document.getElementById('retrievedSectionsList');
    
    if (data.retrieved_sections && data.retrieved_sections.length > 0) {
        retrievedSections.style.display = 'block';
        retrievedSectionsList.innerHTML = data.retrieved_sections.map((section, idx) => `
            <div class="alert alert-info mb-2">
                <small class="badge bg-primary me-2">${idx + 1}</small>
                <strong>${escapeHtml(section.title)}</strong>
                <small class="text-muted ms-2">(Relevance: ${section.relevance.toFixed(2)})</small>
            </div>
        `).join('');
    } else {
        retrievedSections.style.display = 'none';
    }
    
    // Display AI analysis
    const aiAnalysis = document.getElementById('aiAnalysis');
    aiAnalysis.innerHTML = formatMarkdown(data.research);
    
    // Display cited sections
    const citedSections = document.getElementById('citedSections');
    const citedSectionsList = document.getElementById('citedSectionsList');
    
    if (data.cited_sections && data.cited_sections.length > 0) {
        citedSections.style.display = 'block';
        citedSectionsList.innerHTML = data.cited_sections.map(section => `
            <span class="badge bg-success me-2 mb-2">${escapeHtml(section)}</span>
        `).join('');
    } else {
        citedSections.style.display = 'none';
    }
    
    // Scroll to results
    researchResults.scrollIntoView({behavior: 'smooth', block: 'start'});
}

/**
 * Quick search helper
 */
function quickSearch(query) {
    researchQuery.value = query;
    researchQuery.focus();
    performResearch(query);
}

/**
 * Export results
 */
function exportResults() {
    if (!lastResearchResult) {
        alert('No results to export');
        return;
    }
    
    const exportText = `
LEGAL RESEARCH REPORT
Generated by LegalMind AI
Date: ${new Date().toLocaleString()}

QUERY:
${lastResearchResult.query}

RETRIEVED SECTIONS:
${lastResearchResult.retrieved_sections ? 
    lastResearchResult.retrieved_sections.map((s, i) => 
        `${i+1}. ${s.title} (Relevance: ${s.relevance.toFixed(2)})`
    ).join('\n') : 'None'}

ANALYSIS:
${lastResearchResult.research}

CITED SECTIONS:
${lastResearchResult.cited_sections ? 
    lastResearchResult.cited_sections.join(', ') : 'None'}
`;
    
    // Download as text file
    const blob = new Blob([exportText], {type: 'text/plain'});
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `legal_research_${Date.now()}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
}

/**
 * Format markdown-style text
 */
function formatMarkdown(text) {
    let formatted = escapeHtml(text);
    
    // Headers
    formatted = formatted.replace(/^## (.*?)$/gm, '<h5 class="text-primary mt-4 mb-3 border-bottom pb-2">$1</h5>');
    formatted = formatted.replace(/^# (.*?)$/gm, '<h4 class="text-white mt-4 mb-3">$1</h4>');
    
    // Bold
    formatted = formatted.replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>');
    
    // Lists
    formatted = formatted.replace(/^- (.*?)$/gm, '<li>$1</li>');
    formatted = formatted.replace(/(<li>.*?<\/li>)/s, '<ul class="mb-3">$1</ul>');
    
    // Numbered lists
    formatted = formatted.replace(/^\d+\. (.*?)$/gm, '<li>$1</li>');
    
    // Line breaks
    formatted = formatted.replace(/\n\n/g, '</p><p>');
    formatted = '<p>' + formatted + '</p>';
    formatted = formatted.replace(/\n/g, '<br>');
    
    // Section references - make them stand out
    formatted = formatted.replace(/(Section\s+\d+[A-Z]*\s+[A-Z]{2,})/g, 
        '<span class="badge bg-warning text-dark">$1</span>');
    
    return formatted;
}

/**
 * Escape HTML
 */
function escapeHtml(text) {
    const div = document.createElement('div');
    div.textContent = text;
    return div.innerHTML;
}
